export function getLocalizedTemplateName(templateOrName: { name?: string; id?: string } | string, lang: Language): string {
  const rawName = typeof templateOrName === 'string' ? templateOrName : templateOrName.name || '';
  if (!rawName) return '';

  if (lang === 'fr') return rawName;

  if (TEMPLATE_NAMES_MAP[rawName]) {
    return TEMPLATE_NAMES_MAP[rawName][lang] || rawName;
  }

  // Pattern: "Modèle X — Details..." -> "Template X — Details..." / "النموذج X — ..."
  const match = rawName.match(/^Modèle\s+(\d+)(.*)$/i);
  if (match) {
    const num = match[1];
    const rest = match[2];
    if (lang === 'en') {
      return `Template ${num}${rest}`;
    }
    if (lang === 'ar') {
      return `النموذج ${num}${rest}`;
    }
  }

  return rawName;
}

